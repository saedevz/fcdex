import { join } from "node:path";
import {
  buildInsert,
  chunk,
  parseDump,
  sanitizeDump,
  splitStatements,
} from "./parse.js";

const sqlPath = process.argv[2] ?? process.env.FCD_IMPORT_SQL ?? "";

if (!sqlPath) {
  console.error("✗ Usage: bun src/db/import/index.ts <dump.sql|->");
  process.exit(1);
}

const raw =
  sqlPath === "-"
    ? await Bun.stdin.text()
    : await Bun.file(
        sqlPath.startsWith("/") ? sqlPath : join(process.cwd(), sqlPath),
      ).text();

const parsed = parseDump(sanitizeDump(raw));
const ddlStatements = splitStatements(parsed.ddl);
const dataBlocks = parsed.blocks;

const { PGlite } = await import("@electric-sql/pglite");

const dataDir =
  process.env.FCD_PGLITE_DIR ?? join(process.cwd(), ".not-committed");

console.log(`[Import] PGlite data dir: ${dataDir}`);
console.log(`[Import] DDL statements: ${ddlStatements.plain.length}`);
console.log(
  `[Import] COPY blocks: ${dataBlocks.length} (${dataBlocks.reduce((sum, block) => sum + block.rows.length, 0)} rows)`,
);

const db = new PGlite(dataDir);

async function run(statement: string): Promise<void> {
  await db.exec(statement);
}

console.log("[Import] Executing DDL...");

for (const statement of ddlStatements.plain) {
  try {
    await run(statement);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);

    if (message.includes("already exists")) continue;

    console.error(`[Import] ✗ DDL failed: ${statement.slice(0, 120)}...`);
    console.error(`[Import] ✗ ${message}`);
    await db.close();
    process.exit(1);
  }
}

console.log("[Import] ✓ DDL complete. Importing COPY data...");

const CHUNK_SIZE = 1000;

for (const block of dataBlocks) {
  if (block.rows.length === 0) continue;

  for (const part of chunk(block.rows, CHUNK_SIZE)) {
    const insert = buildInsert(block, part);

    if (!insert) continue;

    try {
      await run(insert);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);

      console.error(`[Import] ✗ COPY ${block.table} failed: ${message}`);
      console.error(`[Import] ✗ first row: ${JSON.stringify(part[0])}`);
      await db.close();
      process.exit(1);
    }
  }

  console.log(`[Import] ✓ ${block.table}: ${block.rows.length} rows`);
}

console.log("[Import] Applying foreign key constraints...");

for (const statement of ddlStatements.foreignKeys) {
  try {
    await run(statement);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);

    if (message.includes("already exists")) continue;

    console.error(`[Import] ✗ FK failed: ${message}`);
    console.error(`[Import] ✗ ${statement.slice(0, 120)}...`);
    await db.close();
    process.exit(1);
  }
}

console.log("[Import] Ensuring FCDex additive columns...");

const additiveColumns = [
  'ALTER TABLE "public"."trade" ADD COLUMN IF NOT EXISTS "status" text;',
  'ALTER TABLE "public"."trade" ADD COLUMN IF NOT EXISTS "expires_at" timestamptz;',
  'ALTER TABLE "public"."trade" ADD COLUMN IF NOT EXISTS "resolved_at" timestamptz;',
];

const additiveTables = [
  `CREATE TABLE IF NOT EXISTS "public"."blacklistedguild" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "discord_id" bigint NOT NULL,
    "reason" text,
    "date" timestamptz,
    "moderator_id" bigint,
    CONSTRAINT "blacklistedguild_pkey" PRIMARY KEY ("id")
  );`,
  `CREATE UNIQUE INDEX IF NOT EXISTS "blacklistedguild_discord_id_key" ON "public"."blacklistedguild"("discord_id");`,
  `CREATE TABLE IF NOT EXISTS "public"."spawnwave" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "guild_id" bigint NOT NULL,
    "wave_key" varchar(64) NOT NULL,
    "rarity_floor" double precision NOT NULL,
    "rarity_ceiling" double precision NOT NULL,
    "size" integer NOT NULL,
    "status" varchar(16) NOT NULL DEFAULT 'active',
    "created_at" timestamptz NOT NULL DEFAULT now(),
    "ended_at" timestamptz,
    CONSTRAINT "spawnwave_pkey" PRIMARY KEY ("id")
  );`,
  `CREATE UNIQUE INDEX IF NOT EXISTS "spawnwave_wave_key_key" ON "public"."spawnwave"("wave_key");`,
  `CREATE INDEX IF NOT EXISTS "spawnwave_guild_id_created_at_idx" ON "public"."spawnwave"("guild_id", "created_at");`,
  `CREATE TABLE IF NOT EXISTS "public"."spawnwaveentry" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "wave_id" bigint NOT NULL,
    "ball_id" bigint NOT NULL,
    "special_id" bigint,
    "spawn_key" varchar(64),
    "instance_id" bigint,
    "reward" bigint NOT NULL DEFAULT 0,
    "caught" boolean NOT NULL DEFAULT false,
    "created_at" timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT "spawnwaveentry_pkey" PRIMARY KEY ("id")
  );`,
  `CREATE INDEX IF NOT EXISTS "spawnwaveentry_wave_id_idx" ON "public"."spawnwaveentry"("wave_id");`,
  `ALTER TABLE "public"."spawnwaveentry" ADD CONSTRAINT "spawnwaveentry_wave_id_fkey" FOREIGN KEY ("wave_id") REFERENCES "public"."spawnwave"("id") ON DELETE CASCADE ON UPDATE CASCADE;`,
];

for (const statement of additiveColumns) {
  await run(statement);
}

for (const statement of additiveTables) {
  try {
    await run(statement);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);

    if (message.includes("already exists")) continue;
    throw error;
  }
}

console.log("[Import] Syncing identity sequences...");

const tables = [
  ...new Set(
    dataBlocks
      .filter((block) => block.rows.length > 0)
      .map((block) => block.table),
  ),
];

for (const table of tables) {
  try {
    await run(
      `SELECT setval(pg_get_serial_sequence('"public"."${table}"', 'id'), COALESCE((SELECT MAX("id") FROM "public"."${table}"), 1));`,
    );
  } catch {
    // tables without bigint id columns are skipped
  }
}

const counts = await db.query<{ table_name: string; rows: string }>(
  `SELECT relname AS table_name, n_live_tup AS rows FROM pg_stat_user_tables ORDER BY n_live_tup DESC LIMIT 8;`,
);

console.log("[Import] Top tables:");

for (const row of counts.rows) {
  console.log(`  • ${row.table_name}: ${row.rows}`);
}

await db.close();

console.log("[Import] ✓ BallsDex dump imported into PGlite.");
